"""Drivable-area gate for candidate avoidance paths.

The FOT core accepts only a scalar max_road_width_l/r and its
is_valid_path() checks speed, acceleration, curvature and obstacle
collision -- never whether a candidate stays on the track.  On a circuit
whose width varies by a factor of ~3.7 that constant is either too small
to avoid anything or large enough to place a manoeuvre outside the
boundary, so it cannot be made both safe and useful by tuning.

This module supplies the missing constraint as a *post-hoc* gate: the
table generated by scripts/generate_track_width.py gives the measured
distance from every raceline waypoint to the track boundary on each side,
and a path is rejected outright if any of its points would put the vehicle
body past that boundary.  Rejection makes the node publish an empty
avoidance trajectory, which simple_pure_pursuit already treats as "follow
the untouched reference trajectory".

Being a gate rather than a search constraint, it cannot make a better path
be found -- it only guarantees that a bad one is never followed, whatever
produced it (an off-track sample, a poor local spline fit, or a lateral
quintic overshooting past its target offset).
"""
import csv

import numpy as np


class TrackWidthTable:
    """Per-waypoint drivable lateral margins, loaded from a CSV table."""

    def __init__(self, x, y, w_left, w_right, source=""):
        self.x = np.asarray(x, dtype=np.float64)
        self.y = np.asarray(y, dtype=np.float64)
        self.w_left = np.asarray(w_left, dtype=np.float64)
        self.w_right = np.asarray(w_right, dtype=np.float64)
        self.source = source

    def __len__(self):
        return len(self.x)

    @classmethod
    def from_csv(cls, path):
        """Load a table written by scripts/generate_track_width.py.

        Raises ValueError on a malformed or too-short file so the caller can
        fail safe instead of running with a partially valid constraint.
        """
        xs, ys, wls, wrs = [], [], [], []
        with open(path, newline="") as f:
            reader = csv.DictReader(f)
            required = {"x", "y", "w_left", "w_right"}
            if reader.fieldnames is None or \
                    not required.issubset(reader.fieldnames):
                raise ValueError(
                    f"{path}: expected columns {sorted(required)}, got "
                    f"{reader.fieldnames}")
            for row in reader:
                xs.append(float(row["x"]))
                ys.append(float(row["y"]))
                wls.append(float(row["w_left"]))
                wrs.append(float(row["w_right"]))
        if len(xs) < 2:
            raise ValueError(f"{path}: fewer than 2 rows")
        return cls(xs, ys, wls, wrs, source=path)

    def mismatch_against(self, trajectory_points, tolerance):
        """Return a message if the table does not describe these waypoints.

        The table is only valid for the exact raceline it was generated
        from.  simple_trajectory_generator republishes its CSV one-to-one,
        so a mismatch means the launched raceline and the table have
        diverged -- in which case the margins would be read off the wrong
        part of the track, which is worse than having no gate at all.
        Returns None when they agree.
        """
        if len(trajectory_points) != len(self.x):
            return (f"waypoint count differs: reference trajectory has "
                    f"{len(trajectory_points)}, table has {len(self.x)}")

        px = np.array([p.pose.position.x for p in trajectory_points])
        py = np.array([p.pose.position.y for p in trajectory_points])
        deviation = np.hypot(px - self.x, py - self.y)
        worst = int(np.argmax(deviation))
        if deviation[worst] > tolerance:
            return (f"waypoint {worst} is {deviation[worst]:.2f}m from the "
                    f"table entry (tolerance {tolerance:.2f}m)")
        return None

    def first_violation(self, xs, ys, index_lo, index_hi,
                        half_width, margin):
        """First path point that leaves the drivable area, or None.

        Only waypoints in [index_lo, index_hi] are considered.  The window
        matters: this raceline starts with a garage out-lap and then closes
        on itself (waypoint 130 coincides with waypoint 12), so a global
        nearest-waypoint lookup would be ambiguous where the loop meets.
        The caller passes the same window it fed to the planner, which by
        construction covers the whole candidate path.

        Returns a dict describing the violation (for logging), or None if
        every point is inside.
        """
        lo = max(0, int(index_lo))
        hi = min(len(self.x) - 1, int(index_hi))
        if hi - lo < 1:
            return {"reason": "no reference segments in window",
                    "index": lo, "offset": 0.0, "allowed": 0.0, "side": "n/a"}

        a = np.stack([self.x[lo:hi], self.y[lo:hi]], axis=1)
        b = np.stack([self.x[lo + 1:hi + 1], self.y[lo + 1:hi + 1]], axis=1)
        ab = b - a
        length_sq = (ab ** 2).sum(axis=1)
        length_sq[length_sq == 0.0] = 1e-12

        for path_index, (px, py) in enumerate(zip(xs, ys)):
            p = np.array([float(px), float(py)])
            t = np.clip(((p - a) * ab).sum(axis=1) / length_sq, 0.0, 1.0)
            closest = a + t[:, None] * ab
            k = int(np.argmin(np.hypot(closest[:, 0] - p[0],
                                       closest[:, 1] - p[1])))

            # Signed lateral offset from the raceline: positive means left
            # of the direction of travel, matching the convention the width
            # table was measured with.
            seg = ab[k]
            seg_len = float(np.hypot(seg[0], seg[1]))
            if seg_len < 1e-9:
                continue
            rel = p - a[k]
            offset = float(seg[0] * rel[1] - seg[1] * rel[0]) / seg_len

            # Interpolate the margin along the segment the point projects to.
            ratio = float(t[k])
            w_left = float(self.w_left[lo + k] +
                           ratio * (self.w_left[lo + k + 1] -
                                    self.w_left[lo + k]))
            w_right = float(self.w_right[lo + k] +
                            ratio * (self.w_right[lo + k + 1] -
                                     self.w_right[lo + k]))

            allowed_left = max(0.0, w_left - half_width - margin)
            allowed_right = max(0.0, w_right - half_width - margin)

            if offset > allowed_left:
                return {"reason": "left of drivable area",
                        "path_index": path_index, "index": lo + k,
                        "offset": offset, "allowed": allowed_left,
                        "side": "left"}
            if -offset > allowed_right:
                return {"reason": "right of drivable area",
                        "path_index": path_index, "index": lo + k,
                        "offset": -offset, "allowed": allowed_right,
                        "side": "right"}
        return None
